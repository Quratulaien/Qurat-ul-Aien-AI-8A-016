"""
Part C — the two-map activity (CDB601220, Week 5). Synthetic course data.

    python3 partC_maps.py            build Map A (count) and Map B (rate) + self-checks
    python3 partC_maps.py --record   run ONE real reader; appends to partC_reader_results.csv
    python3 partC_maps.py --score    mean overlap across your readers (needs ≥ 5 real rows)

The maps differ ONLY in the denominator: same boundaries, same Jenks 5-class
scheme, same ramp, same labels. Results are never generated by this script.
"""
import sys
from pathlib import Path

import matplotlib
import numpy as np
import pandas as pd

import geolib
from geolib import PALETTE, style_defaults
from w5common import D, HERE, PER, SYNTH

RESULTS = HERE / "partC_reader_results.csv"
MAP_A, MAP_B = HERE / "partC_mapA_count.png", HERE / "partC_mapB_rate.png"


def load():
    feats = geolib.read_geojson(D / "districts.geojson")
    cc = pd.read_csv(D / "county_crime.csv")
    cc["rate"] = cc.crimes_reported / cc.population * PER
    matched = [f for f in feats if f["code"] in set(cc.code)]
    left_out = sorted({f["code"] for f in feats} - set(cc.code))
    unmatched_rows = sorted(set(cc.code) - {f["code"] for f in feats})
    return feats, matched, cc, left_out, unmatched_rows


def draw_map(path, matched, cc, col, legend_title, fmt, title):
    import matplotlib.pyplot as plt
    style_defaults()
    fig, ax = plt.subplots(figsize=(8, 10))
    geolib.choropleth(ax, matched, dict(zip(cc.code, cc[col])), "natural", 5,
                      legend_title=legend_title, fmt=fmt, legend_anchor=(1.0, 1.0))
    lat_ts = float(np.mean([p[1] for f in matched for p in f["ring"]]))
    e = geolib.breaks(cc[col], "natural", 5)
    cls = dict(zip(cc.code, geolib.class_of(cc[col], e)))
    names = dict(zip(cc.code, cc.county))
    for f in matched:
        x, y = geolib.equal_area_xy(*geolib.representative_point(f["ring"]), lat_ts=lat_ts)
        px, py = geolib.equal_area_xy([p[0] for p in f["ring"]], [p[1] for p in f["ring"]],
                                      lat_ts=lat_ts)
        narrow = (max(px) - min(px)) < 0.6 * (max(py) - min(py)) and (max(px) - min(px)) < 160
        ax.text(x, y, names[f["code"]], ha="center", va="center", fontsize=8,
                rotation=90 if narrow else 0, fontweight="bold",
                color="white" if cls[f["code"]] >= 3 else PALETTE["ink"])
    ax.set_title(title, fontsize=12, loc="left")
    fig.text(0.01, 0.01, f"{SYNTH} (county_crime.csv; boundaries districts.geojson D01–D20). "
             "Lambert equal-area. Jenks, 5 classes.\nPolygons D21–D24 have no county record and are "
             "left out of the map.", fontsize=6.5, color=PALETTE["ink_soft"])
    fig.savefig(path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def build():
    feats, matched, cc, left_out, unmatched_rows = load()
    print(f"join: {len(cc)} counties, {len(feats)} polygons; matched {len(matched)}; county rows "
          f"unmatched {len(unmatched_rows)}; polygons with no county {len(left_out)} {left_out} -> "
          "LEFT OUT of both maps (no data), stated in the caption")
    r = np.corrcoef(cc.crimes_reported, cc.population)[0, 1]
    tc = cc.nlargest(3, "crimes_reported").county.tolist()
    tr = cc.nlargest(3, "rate").county.tolist()
    rk_c = cc.crimes_reported.rank(ascending=False, method="first")
    rk_r = cc.rate.rank(ascending=False, method="first")
    moved = cc[(rk_c - rk_r).abs() >= 3]
    print(f"r(crimes, population) {r:+.3f}; top 3 by count {tc}; by rate {tr}; overlap "
          f"{len(set(tc) & set(tr))}; counties moving ≥3 places: {len(moved)} {moved.county.tolist()}")
    for n in ("Elmsworth", "Hollowfield"):
        row = cc[cc.county == n].iloc[0]
        print(f"   {n}: population {row.population:,}; count rank {int(rk_c[row.name])} -> rate rank "
              f"{int(rk_r[row.name])}")
    assert round(r, 3) == 0.935 and tc == ["Dunmere", "Pellbrook", "Grimsby"]
    assert tr == ["Hollowfield", "Netherby", "Elmsworth"] and len(moved) == 7
    # small-denominator warning for the debrief
    for n in tr:
        row = cc[cc.county == n].iloc[0]
        hw = 1.96 * np.sqrt(row.crimes_reported) / row.population * PER
        print(f"   {n}: {row.crimes_reported} crimes in {row.population:,} -> {row.rate:,.0f} ± {hw:,.0f} per 100k")
    draw_map(MAP_A, matched, cc, "crimes_reported", "Crimes reported\n(count)", "{:,.0f}",
             "Map A · Crimes reported, by county")
    draw_map(MAP_B, matched, cc, "rate", "Crimes reported per\n100,000 residents", "{:,.0f}",
             "Map B · Crimes per 100,000 residents, by county")
    print(f"saved {MAP_A.name}, {MAP_B.name} (show A first, then B)")


def ask_three(prompt, valid):
    while True:
        ans = input(prompt).strip()
        picks = [p.strip().title() for p in ans.replace(";", ",").split(",") if p.strip()]
        bad = [p for p in picks if p not in valid]
        if len(picks) == 3 and not bad and len(set(picks)) == 3:
            return picks
        print(f"  need exactly three different county names from the map; not recognised: {bad}")


def record():
    _, _, cc, _, _ = load()
    valid = set(cc.county)
    print("Show the reader Map A ONLY (partC_mapA_count.png). Ask: 'Which three counties would you "
          "send extra police to, and why?'\nType their three names separated by commas. Do not "
          "let them revise this answer later.")
    reader = input("Reader id (e.g. R1 — not a full name): ").strip() or "R?"
    a = ask_three("Map A — their three: ", valid)
    why_a = input("Map A — their reason, in a few words: ").strip()
    print("Now show Map B (partC_mapB_rate.png). Same question.")
    b = ask_three("Map B — their three: ", valid)
    why_b = input("Map B — their reason, in a few words: ").strip()
    row = pd.DataFrame([{"reader": reader, "mapA_1": a[0], "mapA_2": a[1], "mapA_3": a[2],
                         "mapB_1": b[0], "mapB_2": b[1], "mapB_3": b[2],
                         "overlap": len(set(a) & set(b)), "reason_A": why_a, "reason_B": why_b,
                         "recorded_at": pd.Timestamp.now().strftime("%Y-%m-%d %H:%M")}])
    row.to_csv(RESULTS, mode="a", header=not RESULTS.exists(), index=False)
    print(f"saved: overlap {row.overlap.iloc[0]} -> {RESULTS.name}")


def score():
    if not RESULTS.exists():
        sys.exit("partC_reader_results.csv not found — run `python3 partC_maps.py --record` once "
                 "per real reader (at least five). Results are never generated.")
    df = pd.read_csv(RESULTS)
    _, _, cc, _, _ = load()
    tc = set(cc.nlargest(3, "crimes_reported").county)
    tr = set(cc.nlargest(3, "rate").county)
    print(f"readers: {len(df)}" + ("   (WARNING: the brief requires at least 5)" if len(df) < 5 else ""))
    for r in df.itertuples():
        A = {r.mapA_1, r.mapA_2, r.mapA_3}
        B = {r.mapB_1, r.mapB_2, r.mapB_3}
        print(f"  {r.reader}: A {sorted(A)} | B {sorted(B)} | overlap {r.overlap} | "
              f"A matches count top-3: {len(A & tc)}/3, B matches rate top-3: {len(B & tr)}/3")
    print(f"mean overlap {df.overlap.mean():.2f} of 3 (sd {df.overlap.std(ddof=1) if len(df)>1 else 0:.2f}); "
          f"data-implied overlap if readers just pick the darkest three: 0")
    print("One sentence each: Map A is a map of where people live (r = +0.935 with population); "
          "Map B is a map of reported crime per resident — and its top counties are the smallest, "
          "so their rates are the least stable.")


if __name__ == "__main__":
    if "--record" in sys.argv:
        record()
    elif "--score" in sys.argv:
        score()
    else:
        matplotlib.use("Agg")
        build()
